#!/usr/bin/env python3
"""Extract Fort Denison high/low waters from the Transport for NSW tide-table PDF.

Usage: extract-tides.py tide-tables.pdf > ../TideData.js

Needs pdftotext (poppler). Times in the PDF are Sydney local time (AEST/AEDT);
they are converted to UTC epoch seconds so the plugin never deals with DST.
"""
import re, subprocess, sys
from datetime import datetime
from html import unescape
from zoneinfo import ZoneInfo

SYD = ZoneInfo("Australia/Sydney")
MONTHS = {m: i + 1 for i, m in enumerate(
    "January February March April May June July August September October November December".split())}

pdf = sys.argv[1]
bbox = subprocess.run(["pdftotext", "-bbox", pdf, "-"], capture_output=True, text=True, check=True).stdout
pages = bbox.split("<page ")[1:]
word_re = re.compile(r'<word xMin="([\d.]+)" yMin="([\d.]+)" xMax="([\d.]+)" yMax="([\d.]+)">([^<]*)</word>')

events = []
for page in pages:
    words = [(float(a), float(b), float(c), float(d), unescape(t).strip()) for a, b, c, d, t in word_re.findall(page)]
    # Month headers, e.g. "September 2026" (two per page: left and right halves).
    headers = []
    for i, w in enumerate(words[:-1]):
        if w[4] in MONTHS and re.fullmatch(r"20\d\d", words[i + 1][4]) and w[3] - w[1] > 10:
            headers.append((w[0], MONTHS[w[4]], int(words[i + 1][4])))
    if len(headers) != 2:
        continue
    headers.sort()
    times = [w for w in words if re.fullmatch(r"\d{4}", w[4]) and w[3] - w[1] < 10]
    if not times:
        continue
    # The two month blocks are separated by the widest gap between time columns.
    cols = sorted({round(t[0]) for t in times})
    gap = max(range(1, len(cols)), key=lambda i: cols[i] - cols[i - 1])
    split_x = (cols[gap - 1] + cols[gap]) / 2
    heights = [w for w in words if re.fullmatch(r"\d\.\d\d", w[4])]
    days = [w for w in words if re.fullmatch(r"\d{1,2}", w[4]) and w[3] - w[1] > 15]

    for t in times:
        h = min((x for x in heights if abs(x[1] - t[1]) < 1 and 0 < x[0] - t[2] < 8), key=lambda x: x[0], default=None)
        if not h:
            raise SystemExit(f"no height for {t}")
        # Day number sits just left of its time column, at or above the first row.
        cands = [d for d in days if 0 < t[0] - d[2] < 6 and d[1] <= t[1] + 2]
        if not cands:
            raise SystemExit(f"no day for {t}")
        day = max(cands, key=lambda d: d[1])
        month, year = (headers[0][1], headers[0][2]) if t[0] < split_x else (headers[1][1], headers[1][2])
        local = datetime(year, month, int(day[4]), int(t[4][:2]), int(t[4][2:]), tzinfo=SYD)
        events.append((int(local.timestamp()), float(h[4])))

events.sort()
# Sanity: per-day counts and alternation.
out = []
for i, (ts, h) in enumerate(events):
    prev_h = events[i - 1][1] if i > 0 else None
    next_h = events[i + 1][1] if i + 1 < len(events) else None
    ref = prev_h if prev_h is not None else next_h
    high = h > ref
    if prev_h is not None and next_h is not None and (h > prev_h) != (h > next_h):
        print(f"warning: non-alternating at {datetime.fromtimestamp(ts, SYD)}", file=sys.stderr)
    out.append((ts, h, high))

first = datetime.fromtimestamp(out[0][0], SYD).date()
last = datetime.fromtimestamp(out[-1][0], SYD).date()
print(f"{len(out)} events {first} .. {last}", file=sys.stderr)

print("// Generated by scripts/extract-tides.py from the Transport for NSW tide tables")
print("// (Bureau of Meteorology predictions). Fort Denison, Sydney Harbour.")
print("// Each row: [UTC epoch seconds, height in metres, 1 = high water / 0 = low].")
print(f'var source = "Fort Denison, {first.isoformat()} to {last.isoformat()}"')
print("var events = [")
for i in range(0, len(out), 4):
    print("  " + ", ".join(f"[{ts}, {h:.2f}, {1 if hi else 0}]" for ts, h, hi in out[i:i + 4]) + ",")
print("]")
